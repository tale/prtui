#!/bin/sh
# Vendors every scheme iTerm2-Color-Schemes lets us redistribute.
set -eu

upstream=https://github.com/mbadolato/iTerm2-Color-Schemes
root=$(git rev-parse --show-toplevel)
target="$root/crates/prtui-tui/schemes.conf"
credits="$root/crates/prtui-tui/SCHEMES.md"
checkout=$(mktemp -d)
trap 'rm -rf "$checkout"' EXIT

git clone --quiet --depth 1 --filter=blob:none --sparse "$upstream" "$checkout"
git -C "$checkout" sparse-checkout set ghostty
commit=$(git -C "$checkout" rev-parse HEAD)

printf '# Generated by scripts/sync-schemes.sh from %s.\n' "$upstream" > "$target"
cat > "$credits" <<CREDITS
# Bundled schemes

Vendored from [iTerm2-Color-Schemes]($upstream) at \`$commit\`.

| Scheme | License | Source |
| --- | --- | --- |
CREDITS

# licenses.yml is flat: a scheme name, then indented license and source keys.
awk -v q="'" '
  function unquote(value) {
    if (value ~ "^" q) { gsub("^" q "|" q "$", "", value); gsub(q q, q, value) }
    else if (value ~ /^"/) gsub(/^"|"$/, "", value)
    return value
  }
  function flush() {
    if (name != "" && license != "unknown" && license != "nonfree")
      print name "\t" license "\t" unquote(source)
  }
  /^[^ #]/ { flush(); name = unquote(substr($0, 1, length($0) - 1)); license = source = ""; next }
  /^  license:/ { license = unquote(substr($0, 12)) }
  /^  source:/ { source = substr($0, 11) }
  /^    / { source = source " " substr($0, 5) }
  END { flush() }
' "$checkout/licenses.yml" | sort -f | while IFS="$(printf '\t')" read -r name license source; do
  [ -f "$checkout/ghostty/$name" ] || continue
  printf '\n[%s]\n' "$name" >> "$target"
  cat "$checkout/ghostty/$name" >> "$target"
  printf '| %s | %s | %s |\n' "$name" "$license" "$source" >> "$credits"
done

echo "vendored $(grep -c '^\[' "$target") schemes"
