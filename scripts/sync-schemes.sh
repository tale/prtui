#!/bin/sh
# Vendors the Base16 schemes from tinted-theming.
set -eu

upstream=https://github.com/tinted-theming/schemes
root=$(git rev-parse --show-toplevel)
target="$root/crates/prtui-tui/schemes.conf"
credits="$root/crates/prtui-tui/SCHEMES.md"
checkout=$(mktemp -d)
trap 'rm -rf "$checkout"' EXIT

git clone --quiet --depth 1 --filter=blob:none --sparse "$upstream" "$checkout"
git -C "$checkout" sparse-checkout set base16
commit=$(git -C "$checkout" rev-parse HEAD)

# These don't look good in the TUI with invisible components
excluded="boo-shnickle-light horizon-light horizon-terminal-light icy nebula nova
sandcastle sequoia-monochrome-dark sequoia-moonlight-dark sequoia-retro-dark
stella vulcan"

field() {
  sed -n "s/^$1: *//p" "$2" | head -n 1 | sed 's/^"\(.*\)"$/\1/; s/|/\\|/g'
}

printf '# Generated by scripts/sync-schemes.sh from %s.\n' "$upstream" > "$target"
cat > "$credits" <<CREDITS
# Bundled schemes

Vendored from [tinted-theming/schemes]($upstream) at \`$commit\`.

| Scheme | Name | Author |
| --- | --- | --- |
CREDITS

for path in "$checkout"/base16/*.yaml; do
  slug=$(basename "$path" .yaml)
  case " $(echo $excluded) " in *" $slug "*) continue ;; esac
  printf '\n[%s]\n' "$slug" >> "$target"
  cat "$path" >> "$target"
  printf '| `%s` | %s | %s |\n' "$slug" "$(field name "$path")" "$(field author "$path")" >> "$credits"
done

printf '\n## License\n\n```text\n' >> "$credits"
cat "$checkout/LICENSE" >> "$credits"
printf '```\n' >> "$credits"
pnpm exec oxfmt --write "$credits" > /dev/null

echo "vendored $(grep -c '^\[' "$target") schemes"
